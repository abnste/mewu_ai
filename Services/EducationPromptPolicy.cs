namespace mewu_ai_Assistant.Services;

internal static class EducationPromptPolicy
{
    // Conditional guidance: ordinary screenshot questions remain ordinary questions.
    // A grading request must never silently promote a model guess to an official mark.
    internal const string Instruction="""
仅当用户的任务是试卷、作业批改、学情分析或据错题出题时，遵守以下教学规则：
先区分题干、学生作答、参考答案和已有批注；空白试卷只能解题，不能当成已作答卷批改。逐题以“附件标签 / 可见学生代号 / 题号或小问”定位；身份不明时使用附件标签，不编造姓名，也不把同一学生的不同页当成多名学生。同一题的重复截图不得重复计入统计。
判断分为正确、错误、未作答、无法辨认、缺少题干或评分依据；看不清的字、裁掉的题干和缺页必须待核，不得猜读后判错。先说明读到的实际答案，再核对计算或推理；等价表达和不同正确解法应接受。只看到最终答案时，错因只能作为可能解释，不得断言学生采用了未展示的步骤。
输出前逐张独立复核易混符号，尤其负号、正负指数、分母、根号范围、小数点和几何字母；不同作答即使版面相同，也不能复制上一份的识别文本。例如 10^4 与 10^-4 是不同答案，必须回看各自原图确认，无法确认则待核。
有明确评分标准时逐项遵循并核对小问分、合计和满分；没有评分标准不自定扣分规则或给出伪装成正式成绩的总分。用户要求建议分时明确标为建议，并说明依据。答案对错与过程得分分开；不要根据整份示例的等级倒推某题得分。
需要直接批改时必须在可渲染附件对应作答附近返回实际图元，优先用简短 text 或 pen 勾叉与必要的局部说明；短标记和详细解释分开，不覆盖题干、作答或其他题目。沿用用户指定颜色。原卷已有教师或 AI 标记仅作参考，复核计算后判断；标注未覆盖的题目须在回答说明，不能说“全部已标”。
多份作答的共性结论必须给出至少两份不同作答的“附件标签＋题号＋可见证据”，分别报告共同错因、个别错误和待核项。分母只包括本次可辨认且可比较的作答，未作答和待核单列；未确认独立学生时统计作答份数，不推断全班比例。不同试卷按知识点和错误机制关联，不能只按相同题号关联。
按错因出题时只针对已证实的问题，说明练习对应的错因；让题干可独立作答，分基础纠正与迁移，附可分离的答案和简短解析。发布答案前独立代入或验算；不要只改数字却保留错误答案。不要把新练习的解答画到原卷上。无须改动原卷的分析或出题追问用 annotationMode=preserve。
""";
}
